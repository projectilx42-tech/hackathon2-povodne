"""Generate dashboard/static/js/notice_titles.js from docs/NOTICES.md (code -> step, severity, English title).

The table rows are the single source of truth for notice codes (D-M1-05). Re-run after NOTICES.md changes:
    python dashboard/tools/gen_notice_titles.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# acquire table: code | severity | when (CS) | title (EN) | details; other tables: step | code | severity | when | title | details
out = {}
for line in (ROOT / "docs" / "NOTICES.md").read_text(encoding="utf-8").splitlines():
    if not line.startswith("|"):
        continue
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    for off in (0, 1):
        if len(cells) > off + 4 and re.fullmatch(r"`[a-z0-9_]+`", cells[off]) and cells[off + 1] in ("error", "warning", "info"):
            code = cells[off].strip("`")
            out[code] = {"step": cells[0].strip("`") if off == 1 else "acquire", "severity": cells[off + 1], "title": cells[off + 3]}
            break
dest = ROOT / "dashboard" / "static" / "js" / "notice_titles.js"
dest.write_text("// GENERATED by dashboard/tools/gen_notice_titles.py from docs/NOTICES.md - do not edit by hand.\n"
                "export const NOTICE_TITLES = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
print(len(out), "codes ->", dest)
